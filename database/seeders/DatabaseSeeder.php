    private function seedContents(array $sections): void
    {
        foreach ($sections as $section => $fields) {
            foreach ($fields as $key => $value) {
                SiteContent::query()->updateOrCreate(
                    ['section' => $section, 'field_key' => $key, 'locale' => 'fa'],
                    ['value' => $value]
                );
            }
        }
    }
